"""Build native icons from the SVG master. XML generation/check is platform independent.
Install resvg-py==0.5.0 to render PNG and ICNS on any supported host.
"""
import argparse
import io
import struct
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASTER = ROOT / "design/icon/app-icon.svg"
RES = ROOT / "android/app/src/main/res"
SVG = "{http://www.w3.org/2000/svg}"
ET.register_namespace("", SVG[1:-1])
HEADER = '<!-- Generated by scripts/make_icon.py from design/icon/app-icon.svg -->\n'


def vector(paper, fold, notification=False, monochrome=False):
    # The mark spans x=27..74, y=20.5..79. At scale .84 its corners fit the
    # launcher's central 66-dp circle. Notifications use more of their 24-dp canvas.
    size, viewport, offset, scale = (24, 68, -16, 1) if notification else (108, 108, 12, .84)
    fill = "#FFFFFF" if notification or monochrome else "#F8F6EC"
    paths = f'        <path android:fillColor="{fill}" android:fillType="evenOdd" android:pathData="{paper}" />\n'
    if not notification and not monochrome:
        paths += f'        <path android:fillColor="#DDDFD0" android:pathData="{fold}" />\n'
    return HEADER + f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size}dp"
    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
    <group android:translateX="{offset}" android:translateY="{offset}"
        android:scaleX="{scale}" android:scaleY="{scale}">
{paths}    </group>
</vector>
"""


def android_resources(svg):
    paths = [svg.find(f".//{SVG}path[@id='{name}']").attrib["d"] for name in ("paper", "fold")]
    files = {"drawable/ic_launcher_foreground.xml": vector(*paths),
             "drawable/ic_launcher_monochrome.xml": vector(*paths, monochrome=True),
             "drawable/ic_notification.xml": vector(*paths, notification=True)}
    for version in (26, 33):
        mono = '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n' if version == 33 else ""
        files[f"mipmap-anydpi-v{version}/ic_launcher.xml"] = HEADER + f"""<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
{mono}</adaptive-icon>
"""
    return files


def raster_icons(svg):
    from resvg_py import svg_to_bytes

    def render(size, dest):
        svg.set("width", str(size))
        svg.set("height", str(size))
        dest.parent.mkdir(exist_ok=True, parents=True)
        data = svg_to_bytes(svg_string=ET.tostring(svg, encoding="unicode"))
        dest.write_bytes(data)
        if data[:8] != b"\x89PNG\r\n\x1a\n" or struct.unpack(">II", data[16:24]) != (size, size):
            raise ValueError(f"Incorrect PNG output at {dest}")
        return data

    render(1024, ROOT / "assets/AppIcon.png")
    chunks = io.BytesIO()
    for points, standard, retina in ((16, "icp4", "ic11"), (32, "icp5", "ic12"), (128, "ic07", "ic13"),
                                     (256, "ic08", "ic14"), (512, "ic09", "ic10")):
        for factor, code in ((1, standard), (2, retina)):
            suffix = "" if factor == 1 else "@2x"
            data = render(points * factor, ROOT / f"assets/AppIcon.iconset/icon_{points}x{points}{suffix}.png")
            chunks.write(struct.pack(">4sI", code.encode(), 8 + len(data)) + data)
    payload = chunks.getvalue()
    (ROOT / "assets/AppIcon.icns").write_bytes(struct.pack(">4sI", b"icns", 8 + len(payload)) + payload)
    # Stores apply their own mask to the full-bleed 512px artwork.
    tile = svg.find(f"{SVG}rect[@id='tile']")
    tile.attrib.update(x="0", y="0", width="100", height="100", rx="0")
    render(512, ROOT / "design/icon/play-store.png")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-android", action="store_true", help="verify Android XML without the rasterizer")
    args = parser.parse_args()
    svg = ET.parse(MASTER).getroot()
    for name, data in android_resources(svg).items():
        path = RES / name
        if args.check_android:
            if not path.exists() or path.read_text() != data:
                raise SystemExit(f"Stale {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(exist_ok=True, parents=True)
            path.write_text(data)
    if not args.check_android:
        raster_icons(svg)


if __name__ == "__main__":
    main()
