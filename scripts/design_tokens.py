def swift():
    text = HEADER + """import SwiftUI

enum DesignTokens {
    private static func adaptive(_ name: String, _ light: UInt32, _ dark: UInt32) -> Color {
        Color(nsColor: NSColor(name: NSColor.Name("Shengjian." + name)) { appearance in
            let value = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? dark : light
            return NSColor(srgbRed: CGFloat(value >> 16) / 255,
                           green: CGFloat((value >> 8) & 255) / 255,
                           blue: CGFloat(value & 255) / 255, alpha: 1)
        })
    }

"""
    for name, light in TOKENS["light"].items():
        dark = TOKENS["dark"][name]
        text += f'    static let {name} = adaptive("{name}", 0x{light[1:]}, 0x{dark[1:]})\n'
    for group in ("space", "radius"):
        for name, value in TOKENS[group].items():
            text += f"    static let {group}{name.capitalize()}: CGFloat = {value}\n"
    text += f'    static let draftOpacity = {TOKENS["draftOpacity"]}\n\n'
    text += "    enum TypeRole {\n"
    for name in TOKENS["type"]:
        text += f"        case {name}\n"
    text += "\n        var metrics: (CGFloat, Font.TextStyle, Font.Weight) {\n            switch self {\n"
    weights = {"Normal": "regular", "Medium": "medium", "SemiBold": "semibold"}
    for name, role in TOKENS["type"].items():
        text += f'            case .{name}: ({role["size"]}, .{role["swift"]}, .{weights[role["weight"]]})\n'
    return text + """            }
        }
    }
}

struct DesignType: ViewModifier {
    @ScaledMetric private var size: CGFloat
    private let weight: Font.Weight

    init(_ role: DesignTokens.TypeRole) {
        let (points, style, weight) = role.metrics
        _size = ScaledMetric(wrappedValue: points, relativeTo: style)
        self.weight = weight
    }

    func body(content: Content) -> some View {
        content.font(.system(size: size, weight: weight))
    }
}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    check_contrast()
    files = {APP / "java/com/localrecorder/shengjian/ui/theme/DesignTokens.kt": kotlin(),
             ROOT / "Sources/Recorder/DesignTokens.swift": swift()}
    for mode, directory in (("light", "values"), ("dark", "values-night")):
        files[APP / "res" / directory / "colors.xml"] = (
            '<!-- Generated by scripts/design_tokens.py -->\n<resources>\n'
            f'    <color name="background">{TOKENS[mode]["surface"]}</color>\n'
            f'    <color name="launcher_background">{TOKENS["seed"]}</color>\n</resources>\n')
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Regenerate {path.relative_to(ROOT)} with scripts/design_tokens.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
