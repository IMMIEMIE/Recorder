"""Generate the native themes. Run with --check in CI (Python 3, standard library)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "android/app/src/main"
TOKENS = json.loads((ROOT / "design/tokens.json").read_text())
STATUS = ("recording", "connecting", "slow", "complete")
HEADER = "// Generated by scripts/design_tokens.py from design/tokens.json.\n"


def rgb(color):
    return tuple(int(color[i:i + 2], 16) / 255 for i in (1, 3, 5))


def luminance(channels):
    linear = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in channels]
    return sum(v * w for v, w in zip(linear, (0.2126, 0.7152, 0.0722)))


def check_contrast():
    if TOKENS["light"].keys() != TOKENS["dark"].keys():
        raise ValueError("Both palettes need the same roles")
    surfaces = [role for role in TOKENS["light"] if role.startswith("surface")]
    pairs = [(fg, bg, 1) for fg in ("onSurface", "onSurfaceVariant", *STATUS, "error") for bg in surfaces]
    pairs += [(fg, bg, TOKENS["draftOpacity"]) for fg in ("onSurface", "onSurfaceVariant") for bg in ("surface", "surfaceContainerLow")]
    for role in ("primary", "secondary", "tertiary", "error"):
        for suffix in ("", "Container"):
            pairs.append(("on" + role.capitalize() + suffix, role + suffix, 1))
    pairs.append(("inverseOnSurface", "inverseSurface", 1))
    for mode in ("light", "dark"):
        palette = TOKENS[mode]
        ratios = []
        for fg, bg, alpha in pairs:
            back = rgb(palette[bg])
            front = [f * alpha + b * (1 - alpha) for f, b in zip(rgb(palette[fg]), back)]
            low, high = sorted((luminance(front), luminance(back)))
            ratio = (high + 0.05) / (low + 0.05)
            if ratio < 4.5:
                raise ValueError(f"{mode} {fg} / {bg} at {alpha}: {ratio:.2f}:1")
            ratios.append(ratio)
        print(f"{mode}: {len(ratios)} text/background combinations, minimum {min(ratios):.2f}:1")


